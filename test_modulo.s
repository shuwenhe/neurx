package main

func main() {
    // 测试模运算 (%) 操作符
    
    println("======================================================================")
    println("S 语言模运算 (%) 操作符测试")
    println("======================================================================")
    println("")
    
    // 基本模运算测试
    a := 10
    b := 3
    result := a % b
    
    println("测试 1: 基本模运算")
    println("  10 % 3 = " + string(result))
    println("")
    
    // 更多测试
    println("测试 2: 其他模运算")
    r1 := 15 % 4
    r2 := 20 % 6
    r3 := 7 % 7
    r4 := 5 % 2
    println("  15 % 4 = " + string(r1))
    println("  20 % 6 = " + string(r2))
    println("  7 % 7 = " + string(r3))
    println("  5 % 2 = " + string(r4))
    println("")
    
    // 在表达式中使用
    println("测试 3: 在表达式中使用")
    x := 100
    y := 7
    z := x % y
    println("  100 % 7 = " + string(z))
    println("")
    
    println("======================================================================")
    println("✅ 模运算 (%) 操作符支持成功！")
    println("======================================================================")
}
